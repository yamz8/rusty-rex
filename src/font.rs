//! A 5x7 pixel font for the score and the messages, drawn like the sprites.
//!
//! Chrome draws its digits and GAME OVER as pixel art too, and a built-in
//! grid needs no font file or glyph atlas.

use crate::sprites::Sprite;

const GLYPH_HEIGHT: usize = 7;
/// Blank columns between letters.
const SPACING: usize = 1;

const BLANK: [&str; GLYPH_HEIGHT] = ["....."; GLYPH_HEIGHT];


fn glyph(c: char) -> &'static [&'static str; GLYPH_HEIGHT] {
    let c = c.to_ascii_uppercase();
    GLYPHS
        .iter()
        .find(|(g, _)| *g == c)
        .map_or(&BLANK, |(_, rows)| rows)
}

/// Lays out a line of text as one sprite. Letters the font lacks, spaces
/// included, are left blank.
pub fn text(s: &str) -> Sprite {
    let mut rows = vec![String::new(); GLYPH_HEIGHT];
    for (i, c) in s.chars().enumerate() {
        for (row, glyph_row) in rows.iter_mut().zip(glyph(c)) {
            if i > 0 {
                row.push_str(&".".repeat(SPACING));
            }
            row.push_str(glyph_row);
        }
    }
    let rows: Vec<&str> = rows.iter().map(String::as_str).collect();
    Sprite::new(&rows)
}

#[cfg(test)]
mod tests {
    use super::*;

    const GLYPH_WIDTH: usize = 5;

    #[test]
    fn every_glyph_is_five_by_seven() {
        for (c, rows) in GLYPHS {
            for row in rows {
                assert_eq!(row.len(), GLYPH_WIDTH, "{c}");
                assert!(row.chars().all(|p| p == '#' || p == '.'), "{c}");
            }
        }
    }

    #[test]
    fn covers_digits_and_letters() {
        for c in ('0'..='9').chain('A'..='Z') {
            assert!(GLYPHS.iter().any(|(g, _)| *g == c), "{c}");
        }
    }

    #[test]
    fn lines_are_letters_and_gaps() {
        let line = text("Hi 42");
        assert_eq!((line.cols, line.rows), (5 * 6 - 1, GLYPH_HEIGHT));
        assert_eq!(text("hi").runs.len(), text("HI").runs.len());
        assert!(text("   ").runs.is_empty());
    }
}
